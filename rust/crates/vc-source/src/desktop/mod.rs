//! Windows 桌面采集后端选择与公开 [`DesktopSource`]。
//!
//! `dda` 使用 DXGI Desktop Duplication，`wgc` 使用 Windows Graphics Capture；
//! `pattern` 由 `vc-stream` 自行生成，本 crate 明确拒绝。两种后端失败都不
//! 互相回退，`gpu_convert` 失败也不回退 CPU。

mod dda;
mod gpu;
mod util;
mod wgc;

use std::sync::Arc;
use std::sync::atomic::{AtomicU64, Ordering};

use anyhow::{Result, bail};
use serde_json::{Value, json};

use crate::transform::TransformMode;
use crate::{SourceConfig, validate};

use dda::DdaSource;
use wgc::WgcSource;

enum Backend {
    Dda(DdaSource),
    Wgc(WgcSource),
}

impl Backend {
    fn capture(&mut self, destination: &mut [u8]) -> Result<bool> {
        match self {
            Self::Dda(source) => source.capture(destination),
            Self::Wgc(source) => source.capture(destination),
        }
    }

    fn source_dimensions(&self) -> (u32, u32) {
        match self {
            Self::Dda(source) => source.source_dimensions(),
            Self::Wgc(source) => source.source_dimensions(),
        }
    }

    fn adapter_name(&self) -> &str {
        match self {
            Self::Dda(source) => source.adapter_name(),
            Self::Wgc(source) => source.adapter_name(),
        }
    }
}

/// 桌面采集源。只接受 `dda` / `wgc`；输出帧为 packed NV12。
///
/// `capture` 返回 `Ok(false)` 表示在不超过 20 ms 的等待窗口内没有新图像；
/// 任何错误（采集项关闭、帧池重建失败、GPU 转换失败等）都是致命错误，
/// 调用方必须停止，不能由本类型静默换后端或换转换方式。
pub struct DesktopSource {
    config: SourceConfig,
    width: u32,
    height: u32,
    transform: TransformMode,
    skipped: Arc<AtomicU64>,
    backend: Backend,
}

impl DesktopSource {
    /// 打开 DDA/WGC 采集。`width`/`height` 是协商后的 NV12 输出尺寸，
    /// 必须是 2..=8192 的偶数。
    pub fn open(config: &SourceConfig, width: u32, height: u32) -> Result<Self> {
        validate(config)?;
        if !(2..=8192).contains(&width) || !width.is_multiple_of(2) {
            bail!("output width must be an even value in 2..=8192 (got {width})");
        }
        if !(2..=8192).contains(&height) || !height.is_multiple_of(2) {
            bail!("output height must be an even value in 2..=8192 (got {height})");
        }
        let transform = TransformMode::parse(&config.transform)?;
        let skipped = Arc::new(AtomicU64::new(0));
        let backend = match config.mode.as_str() {
            "dda" => Backend::Dda(DdaSource::open(
                config,
                width,
                height,
                transform,
                skipped.clone(),
            )?),
            "wgc" => Backend::Wgc(WgcSource::open(
                config,
                width,
                height,
                transform,
                skipped.clone(),
            )?),
            "pattern" => {
                bail!("pattern mode is generated by vc-stream, not DesktopSource; use dda or wgc")
            }
            other => bail!("unsupported desktop source mode {other:?}; use dda or wgc"),
        };
        Ok(Self {
            config: config.clone(),
            width,
            height,
            transform,
            skipped,
            backend,
        })
    }

    /// 采集一帧到 `destination`。长度必须至少为 `width*height*3/2`。
    pub fn capture(&mut self, destination: &mut [u8]) -> Result<bool> {
        let required = self.frame_bytes();
        if destination.len() < required {
            bail!(
                "NV12 destination too small: need {required} bytes, got {}",
                destination.len()
            );
        }
        self.backend.capture(destination)
    }

    fn frame_bytes(&self) -> usize {
        self.width as usize * self.height as usize * 3 / 2
    }

    /// 实际使用的 GPU、丢弃的源帧、源/输出尺寸与当前配置。
    pub fn stats(&self) -> Value {
        let (source_width, source_height) = self.backend.source_dimensions();
        json!({
            "mode": self.config.mode,
            "pattern": self.config.pattern,
            "output": self.config.output,
            "window": self.config.window,
            "transform": self.transform.as_str(),
            "gpu_convert": self.config.gpu_convert,
            "gpu": self.backend.adapter_name(),
            "source_width": source_width,
            "source_height": source_height,
            "output_width": self.width,
            "output_height": self.height,
            "frame_bytes": self.frame_bytes(),
            "source_skipped": self.skipped.load(Ordering::Relaxed),
        })
    }
}
