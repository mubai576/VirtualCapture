//! VirtualCapture Rust 采集源。
//!
//! 纯几何/像素转换在 [`transform`]（可移植、全整数）；Windows 桌面采集由
//! [`DesktopSource`] 提供：
//!
//! - `dda`：DXGI Desktop Duplication，按 `output` 显示器序号取屏；
//! - `wgc`：Windows Graphics Capture，`window` 非空时按标题子串取窗口，
//!   否则按 `output` 显示器序号取屏；
//! - `pattern`：由 `vc-stream` 生成，本 crate 不实现，`DesktopSource::open`
//!   会显式拒绝。
//!
//! 采集失败是致命错误；`capture` 返回 `Ok(false)` 只表示在不超过 20 ms 的
//! 等待窗口内没有新图像（例如输出空闲、仅指针更新或 WGC 帧池正在重建）。
//! 不允许静默回退：DDA/WGC 不互相兜底，`gpu_convert=true` 时 GPU 初始化或
//! 转换失败会让打开/采集直接报错，不会改走 CPU。

use anyhow::{Result, bail};
use serde::{Deserialize, Serialize};

pub mod transform;

#[cfg(windows)]
mod desktop;
#[cfg(windows)]
pub use desktop::DesktopSource;

/// `mode` 允许值。
pub const MODES: [&str; 3] = ["pattern", "dda", "wgc"];
/// `pattern` 允许值，与 `sender/pattern.h` / `vc-stream` 的五种图案一致。
pub const PATTERNS: [&str; 5] = ["counter", "checker", "rings", "noise", "motion"];
/// `transform` 允许值。
pub const TRANSFORMS: [&str; 4] = ["crop", "fit", "fill", "stretch"];

/// 采集源配置。字段与旧原生 sender 的 `--mode/--pattern/--output/--wgc-window/
/// --transform/--gpu-convert` 一一对应。
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(default, deny_unknown_fields)]
pub struct SourceConfig {
    /// `pattern` | `dda` | `wgc`。
    pub mode: String,
    /// 测试图案名（`pattern` 模式由 vc-stream 使用）。
    pub pattern: String,
    /// DDA/WGC 显示器序号 0..=15；WGC 窗口模式忽略。
    pub output: u32,
    /// WGC 窗口标题子串；空表示整屏。DDA 模式必须为空。
    pub window: String,
    /// `crop` | `fit` | `fill` | `stretch`。
    pub transform: String,
    /// 显式启用 D3D11 compute shader 的 BGRA→NV12 转换；失败不回退 CPU。
    pub gpu_convert: bool,
}

impl Default for SourceConfig {
    fn default() -> Self {
        Self {
            mode: "pattern".into(),
            pattern: "motion".into(),
            output: 0,
            window: String::new(),
            transform: "crop".into(),
            gpu_convert: false,
        }
    }
}

/// 校验 [`SourceConfig`]。只检查配置本身；显示器/窗口是否存在、尺寸是否支持
/// 由 [`DesktopSource::open`] 在真正建立采集时检查。
pub fn validate(config: &SourceConfig) -> Result<()> {
    if !MODES.contains(&config.mode.as_str()) {
        bail!(
            "mode must be one of pattern/dda/wgc (got {:?})",
            config.mode
        );
    }
    if !PATTERNS.contains(&config.pattern.as_str()) {
        bail!(
            "pattern must be one of counter/checker/rings/noise/motion (got {:?})",
            config.pattern
        );
    }
    if config.output > 15 {
        bail!("output must be 0..15 (got {})", config.output);
    }
    let window_chars = config.window.chars().count();
    if window_chars > 128 {
        bail!("window must be at most 128 characters (got {window_chars})");
    }
    if config.window.chars().any(|ch| (ch as u32) < 0x20) {
        bail!("window must be a single-line string without control characters");
    }
    if !TRANSFORMS.contains(&config.transform.as_str()) {
        bail!(
            "transform must be one of crop/fit/fill/stretch (got {:?})",
            config.transform
        );
    }
    if config.mode != "wgc" && !config.window.is_empty() {
        bail!(
            "window requires wgc mode; dda captures a monitor and pattern/file modes ignore windows"
        );
    }
    if config.mode == "pattern" && config.gpu_convert {
        bail!(
            "gpu_convert is only supported for dda/wgc; pattern frames are generated by vc-stream"
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn defaults_match_native_cli_defaults() {
        let config = SourceConfig::default();
        assert_eq!(config.mode, "pattern");
        assert_eq!(config.pattern, "motion");
        assert_eq!(config.output, 0);
        assert_eq!(config.window, "");
        assert_eq!(config.transform, "crop");
        assert!(!config.gpu_convert);
        validate(&config).unwrap();
    }

    #[test]
    fn serde_defaults_and_unknown_fields() {
        let config: SourceConfig = serde_json::from_str("{}").unwrap();
        assert_eq!(config.mode, "pattern");
        let config: SourceConfig =
            serde_json::from_str(r#"{"mode":"dda","gpu_convert":true}"#).unwrap();
        assert_eq!(config.mode, "dda");
        assert!(config.gpu_convert);
        assert!(serde_json::from_str::<SourceConfig>(r#"{"unknown":1}"#).is_err());

        let encoded = serde_json::to_value(SourceConfig::default()).unwrap();
        assert_eq!(encoded["pattern"], "motion");
    }

    #[test]
    fn rejects_invalid_values() {
        let mut config = SourceConfig {
            mode: "dda".into(),
            window: "notepad".into(),
            ..SourceConfig::default()
        };
        assert!(validate(&config).is_err());

        config.mode = "wgc".into();
        config.window = "note\npad".into();
        assert!(validate(&config).is_err());

        config.window.clear();
        config.transform = "scale".into();
        assert!(validate(&config).is_err());

        config.transform = "crop".into();
        config.output = 16;
        assert!(validate(&config).is_err());

        config.output = 0;
        config.pattern = "unknown".into();
        assert!(validate(&config).is_err());

        config.pattern = "motion".into();
        config.mode = "pattern".into();
        config.gpu_convert = true;
        assert!(validate(&config).is_err());
    }
}
